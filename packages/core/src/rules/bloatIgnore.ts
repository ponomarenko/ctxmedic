import fs from "node:fs";
import path from "node:path";
import type { Rule } from "./types.js";

const HEAVY = [
  "node_modules/", "dist/", "build/", "out/", ".next/", ".nuxt/", "coverage/", "target/", "vendor/",
  ".venv/", "__pycache__/", "*.min.js", "*.map",
  "package-lock.json", "pnpm-lock.yaml", "yarn.lock", "bun.lockb", "Cargo.lock", "poetry.lock", "composer.lock",
];

export const bloatIgnore: Rule = {
  id: "FIN_BLOAT_IGNORE",
  check: ({ root, files, profiles }) => {
    const out = [];
    for (const h of profiles) {
      if (!h.ignoreFile) continue;
      const used = files.some((f) => f.scope === "project" && f.harnesses.includes(h.id)) || fs.existsSync(path.join(root, `.${h.id}`));
      if (!used || fs.existsSync(path.join(root, h.ignoreFile))) continue;
      const present = HEAVY.filter((p) => !p.includes("*") && fs.existsSync(path.join(root, p)));
      if (!present.length) continue;
      out.push({
        ruleId: "FIN_BLOAT_IGNORE" as const,
        severity: "warning" as const,
        message: `${h.name} indexes ${present.join(", ")} because ${h.ignoreFile} is missing`,
        files: present,
        data: { harness: h.id, ignoreFile: h.ignoreFile, present },
        fix: {
          title: `Create ${h.ignoreFile}`,
          ops: [
            {
              kind: "write" as const,
              path: path.join(root, h.ignoreFile),
              content: `# Generated by ctxmedic: keep build output and lockfiles out of the AI index.\n${HEAVY.join("\n")}\n`,
            },
          ],
        },
      });
    }
    return out;
  },
};
